const assert = require('node:assert/strict');
const DraftHistory = require('../../public/draft-history');
const initial = { nodes: [{ id: 'start' }, { id: 'approval' }], edges: [{ from: 'start', to: 'approval' }], visibility: { roles: ['admin'] } };
const history = new DraftHistory(initial, 3);
assert.equal(history.dirty, false);
assert.equal(history.undo(), null);
const deleted = { ...initial, nodes: [initial.nodes[0]], edges: [] };
history.record(deleted);
assert.equal(history.dirty, true);
assert.deepEqual(history.undo(), initial, 'Undo restores the node and its connections together');
assert.equal(history.dirty, false, 'Returning to baseline clears dirty state');
assert.deepEqual(history.redo(), deleted);
history.undo();
history.record({ ...initial, nodes: [...initial.nodes, { id: 'new' }] });
assert.equal(history.redo(), null, 'A new edit invalidates the redo branch');
assert.equal(history.record(JSON.parse(history.current)), false, 'No-op renders do not consume history');
for (let i = 0; i < 10; i++) history.record({ count: i });
assert.equal(history.past.length, 3, 'History is bounded');
history.markSaved({ count: 9 });
assert.equal(history.dirty, false);
assert.equal(history.undo(), null, 'Successful save establishes a new draft boundary');
history.record({ count: 10 });
// A failed API save must not call markSaved: recovery and dirty state remain.
assert.equal(history.dirty, true);
assert.deepEqual(history.undo(), { count: 9 });
initial.nodes[0].id = 'mutated outside';
const immutable = new DraftHistory({ nested: { flag: true } });
const returned = JSON.parse(immutable.current); returned.nested.flag = false;
assert.equal(JSON.parse(immutable.current).nested.flag, true);
console.log('Draft history behavior passed: undo/redo, graph recovery, branching, bounds, saved state and immutable snapshots.');
