const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { templateSchema, contextSchema } = require('../../src/modules/document-templates/document-templates.schema');
const service = require('../../src/modules/document-templates/document-templates.service');
const { renderPdf } = require('../../src/modules/document-templates/document-templates.renderer');
const output = require('../../public/document-output');
const { AppError } = require('../../src/shared/errors');
const { pool } = require('../../src/database/pool');

function fixture(columns = 5, orientation = 'portrait') {
  const text = (id, content, column = 1) => ({ id, type: 'text', content, column, padding: 4, fontSize: 11, fontWeight: '400', alignment: 'left' });
  const template = {
    templateKey: 'pdf_test', name: 'Generic / document: test', source: 'module:example', status: 'draft',
    page: { size: 'A4', orientation, margins: { top: 2, bottom: 2, left: 2, right: 2 }, headerFromTop: 1.25, footerFromBottom: 1.25, headerColumns: 3, footerColumns: 3 },
    regions: {
      header: [text('brand', 'Example organization'), text('title', 'Generic document', 2), text('reference', 'Reference', 3)],
      body: [text('paragraph', 'Long content wraps within the same printable width. '.repeat(4)), { id: 'table', type: 'table', width: 100, printableBorders: true, repeatingSource: 'record.items', columns: Array.from({ length: columns }, (_, i) => ({ id: `col_${i}`, label: `Column ${i}`, width: 100 / columns })), rows: [false, true].map((repeat, r) => ({ id: `row_${r}`, heightCm: .9, repeat, cells: Array.from({ length: columns }, (_, c) => ({ id: `cell_${r}_${c}`, content: `Column ${c + 1}`, binding: repeat ? 'record.items.description' : '', alignment: 'left', padding: 6, colSpan: 1 })) })) }],
      footer: [text('footer', 'Generated by Babyyy'), { id: 'page', type: 'field', binding: 'system.page_number', column: 2 }, { id: 'total', type: 'field', binding: 'system.total_pages', column: 3 }]
    }
  };
  template.regions.body[0].leftIndent = 1;
  return templateSchema.parse(template);
}
async function run() {
  const template = fixture();
  const user = { id: 2, role: 'user', name: 'Viewer' };
  const denied = () => { throw new AppError('Denied', 403); };
  const deps = {
    repository: { find: async () => ({ template, revision: 1 }) },
    departments: { findOrganization: async () => ({ name: 'Example' }) },
    sourceRecords: { getRecord: async () => ({ record: { id: 10, customFields: { visible: 0, secret: 'NEVER OUTPUT' } } }) },
    permissions: { assertModulePageActionAllowed: async () => {}, userFieldPermissions: async () => new Map([['visible', { view: true }], ['secret', { view: false }]]) },
    moduleConfig: { getModuleConfig: async () => ({ fields: [{ fieldKey: 'visible' }, { fieldKey: 'secret' }] }) }
  };
  await assert.rejects(service.resolve('pdf_test', {}, null, deps), { statusCode: 401 });
  await assert.rejects(service.resolve('pdf_test', {}, user, deps), { statusCode: 403 });
  await assert.rejects(service.resolve('pdf_test', { recordId: 10 }, user, { ...deps, permissions: { ...deps.permissions, assertModulePageActionAllowed: denied } }), { statusCode: 403 });
  await assert.rejects(service.resolve('pdf_test', { workflowRequestId: 'REQ' }, user, { ...deps, access: { getRequestView: denied } }), { statusCode: 403 });
  await assert.rejects(service.resolve('pdf_test', { revision: 2 }, { ...user, role: 'admin' }, deps), { statusCode: 409 });
  const allowed = await service.resolve('pdf_test', { recordId: 10 }, user, deps);
  assert.deepEqual(allowed.context.record, { id: 10, visible: 0 });
  assert.equal(output.value('record.visible', allowed.context), '0');
  assert.equal(output.lookup({}, '__proto__.toString'), undefined);
  assert.equal((await service.resolve('pdf_test', {}, { ...user, role: 'admin' }, deps)).reference, 'template');
  assert.equal(contextSchema.safeParse({ recordId: 1, record: { secret: 'x' } }).success, false);
  assert.equal(contextSchema.safeParse({ recordId: 1, zoom: 150 }).success, false);
  const malicious = structuredClone(template); malicious.regions.body.push({ id: 'unsafe', type: 'image', source: 'http://169.254.169.254/' });
  assert.equal(templateSchema.safeParse(malicious).success, false);
  malicious.regions.body.at(-1).source = 'data:image/png;base64,' + Buffer.from('<svg onload="alert(1)"></svg>').toString('base64');
  assert.equal(templateSchema.safeParse(malicious).success, false, 'Disguised SVG is rejected');
  const customerDeps = {
    ...deps, repository: { find: async () => ({ template: { ...template, source: 'module:customers' }, revision: 1 }) },
    moduleConfig: { getModuleConfig: async () => ({ fields: [{ fieldKey: 'description', tableType: 'detail', detailTableName: 'items' }, { fieldKey: 'secret', tableType: 'detail', detailTableName: 'items' }] }) },
    permissions: { ...deps.permissions, userFieldPermissions: async () => new Map([['description', { view: true }]]) },
    customerRepository: { detailRowsByCustomerId: async (_id, fields) => { assert.equal(fields.length, 1); return { items: [{ description: 'Permitted row', secret: 'Hidden' }] }; } }
  };
  assert.deepEqual((await service.resolve('pdf_test', { recordId: 10 }, user, customerDeps)).context.record, { id: 10, items: [{ description: 'Permitted row' }] });
  assert.equal(service.filename('../../Bad\r\nName', 'REQ:1'), 'Bad-Name-REQ-1.pdf');
  const workflowDeps = { ...deps, access: { getRequestView: async () => ({ request: { sourceModuleKey: 'other', sourceRecordId: 10 }, snapshot: { snapshot: {} }, timeline: [] }) } };
  await assert.rejects(service.resolve('pdf_test', { workflowRequestId: 'REQ' }, user, workflowDeps), { statusCode: 422 });
  console.log('PDF access, field redaction, context validation and filename checks passed.');
  if (!process.argv.includes('--render')) return;
  const directory = path.join(__dirname, '../../output/playwright/pdf-backend');
  await fs.mkdir(directory, { recursive: true });
  for (const [columns, orientation, rows] of [[2, 'portrait', 1], [5, 'landscape', 1], [5, 'portrait', 45]]) {
    const sample = fixture(columns, orientation);
    const context = { record: { items: Array.from({ length: rows }, (_, i) => ({ description: `Item ${i + 1} & <escaped>` })) } };
    const pdf = await renderPdf(sample, context, 2);
    assert.equal(pdf.subarray(0, 5).toString(), '%PDF-');
    const filename = path.join(directory, `${orientation}-${columns}-${rows}.pdf`);
    await fs.writeFile(filename, pdf);
    const info = execFileSync('pdfinfo', [filename], { encoding: 'utf8' });
    const pages = Number(info.match(/Pages:\s+(\d+)/)[1]);
    const dimensions = info.match(/Page size:\s+([\d.]+) x ([\d.]+)/).slice(1).map(Number);
    assert.equal(rows === 1 ? pages === 1 : pages > 1, true);
    assert.ok(Math.abs(dimensions[0] - (orientation === 'portrait' ? 595.28 : 841.89)) < 1);
    assert.ok(Math.abs(dimensions[1] - (orientation === 'portrait' ? 841.89 : 595.28)) < 1);
    const content = process.env.PDF_TEST_PYTHON
      ? execFileSync(process.env.PDF_TEST_PYTHON, ['-c', 'import sys; from pypdf import PdfReader; print("\\n".join(p.extract_text() for p in PdfReader(sys.argv[1]).pages))', filename], { encoding: 'utf8' })
      : execFileSync('pdftotext', [filename, '-'], { encoding: 'utf8' });
    assert.ok(content.replace(/\s+/g, ' ').includes('Item 1 & <escaped>'));
    assert.ok(content.replace(/\s+/g, ' ').includes(`Item ${rows} & <escaped>`));
    assert.equal((content.match(/Generated by Babyyy/g) || []).length, pages);
    console.log(`${orientation}, ${columns} columns, ${rows} rows: ${pages} physical A4 page(s), text/header/footer checks passed.`);
  }
  const multi = fixture(2, 'portrait');
  multi.pages = Array.from({ length: 3 }, (_, index) => {
    const page = structuredClone(multi.page); const regions = structuredClone(multi.regions);
    regions.body = [{ id: `physical_${index + 1}`, type: 'text', content: `Physical source page ${index + 1}`, column: 1, padding: 4, fontSize: 11, fontWeight: '400', alignment: 'left' }];
    return { page, regions };
  });
  const multiPdf = await renderPdf(templateSchema.parse(multi), {}, 3); const multiFile = path.join(directory, 'explicit-three-pages.pdf'); await fs.writeFile(multiFile, multiPdf);
  const multiInfo = execFileSync('pdfinfo', [multiFile], { encoding: 'utf8' }); assert.match(multiInfo, /Pages:\s+3\b/, 'explicit pages render without accidental blank pages');
  const multiText = execFileSync('pdftotext', [multiFile, '-'], { encoding: 'utf8' }).replace(/\s+/g, ' ');
  for (let index = 1; index <= 3; index++) { assert.match(multiText, new RegExp(`Physical source page ${index}`)); assert.match(multiText, new RegExp(`\\b${index}\\s+3\\b`), 'page number and total pages resolve per physical page'); }
  console.log('Explicit 3-page A4 output: ordering, page count, page fields and no blank pages passed.');
}
if (require.main === module) run().catch((error) => { console.error(error); process.exitCode = 1; }).finally(() => pool.end());
module.exports = { fixture };
